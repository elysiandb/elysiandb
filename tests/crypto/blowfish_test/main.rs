#[test]
fn cipher_encrypt() {
    for (i, tt) in ENCRYPT_TESTS.iter().enumerate() {
        let c = match blowfish::new_cipher(tt.key) {
            Ok(c) => c,
            Err(err) => panic!("new_cipher({} bytes) = {err}", tt.key.len()),
        };
        let mut ct = vec![0u8; tt.out.len()];
        c.encrypt(&mut ct, tt.input);
        assert_eq!(ct, tt.out, "test vector #{i}");
    }
}

#[test]
fn cipher_key_size() {
    assert_eq!(blowfish::new_cipher(&[]).err(), Some(KeySizeError(0)));
    assert_eq!(
        blowfish::new_cipher(&[0u8; 57]).err(),
        Some(KeySizeError(57))
    );
    assert!(blowfish::new_cipher(&[0u8; 56]).is_ok());
    assert_eq!(KeySizeError(57).to_string(), "invalid blowfish key size 57");
}

#[test]
fn salted_cipher_key_length() {
    assert_eq!(
        blowfish::new_salted_cipher(&[], b"a").err(),
        Some(KeySizeError(0))
    );

    let key = b"012345678901234567890123456789012345678901234567890123456";
    if let Err(err) = blowfish::new_salted_cipher(key, b"a") {
        panic!("new_salted_cipher with long key, gave error {err:?}");
    }
}

#[test]
fn salted_cipher() {
    let mut key = [0u8; 32];
    let mut salt = [0u8; 32];
    for i in 0..key.len() {
        key[i] = i as u8;
        salt[i] = (i + 32) as u8;
    }
    for (i, v) in SALTED_VECTORS.iter().enumerate() {
        let c = blowfish::new_salted_cipher(&key, &salt[..i]).unwrap();
        let mut buf = [0u8; 8];
        c.encrypt_in_place(&mut buf);
        assert_eq!(*v, buf, "{i}");
    }
}

#[test]
fn block_size() {
    let c = blowfish::new_cipher(b"key").unwrap();
    assert_eq!(c.block_size(), blowfish::BLOCK_SIZE);
    assert_eq!(blowfish::BLOCK_SIZE, 8);
}

#[test]
fn expand_key_changes_the_cipher() {
    let key = [7u8; 32];
    let c = blowfish::new_salted_cipher(&key, &[]).unwrap();
    let d = blowfish::new_cipher(&key).unwrap();
    let mut a = [1u8, 2, 3, 4, 5, 6, 7, 8];
    let mut b = a;
    c.encrypt_in_place(&mut a);
    d.encrypt(&mut b, &[1u8, 2, 3, 4, 5, 6, 7, 8]);
    assert_eq!(a, b);

    let mut e = blowfish::new_cipher(&key).unwrap();
    blowfish::expand_key(&key, &mut e);
    let mut x = [1u8, 2, 3, 4, 5, 6, 7, 8];
    e.encrypt_in_place(&mut x);
    assert_ne!(x, a);
}
