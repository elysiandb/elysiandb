func c(label, source, flags string, inputs ...input) jsCase {
	return jsCase{label: label, source: source, flags: flags, inputs: inputs}
}

func span(n int) []int {
	r := make([]int, n+1)
	for i := range r {
		r[i] = i
	}
	return r
}

