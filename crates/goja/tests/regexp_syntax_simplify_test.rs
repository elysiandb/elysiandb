#[test]
fn test_simplify() {
    for (regexp, simple) in SIMPLIFY_TESTS {
        let re = syntax::parse(regexp, MATCH_NL | (PERL & !ONE_LINE))
            .unwrap_or_else(|e| panic!("Parse({:?}) = error {e}", String::from_utf8_lossy(regexp)));
        let s = re.simplify().string();
        assert_eq!(
            String::from_utf8_lossy(&s),
            *simple,
            "Simplify({:?})",
            String::from_utf8_lossy(regexp)
        );
    }
}
